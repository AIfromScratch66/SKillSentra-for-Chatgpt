  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  const attributes = ["aria-label", "placeholder", "title"];
  let language = localStorage.getItem("skillsentra.language") === "en" ? "en" : "zh-CN";

  function translate(source) {
    const value = String(source ?? "");
    if (language !== "en") return value;
    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    const core = value.trim();
    if (!core) return value;
    if (EN[core]) return `${leading}${EN[core]}${trailing}`;

    const step = core.match(/^步骤\s+(\d+)\s*\/\s*(\d+)(?:\s*·\s*(.+))?$/);
    if (step) return `${leading}Step ${step[1]} / ${step[2]}${step[3] ? ` · ${EN[step[3]] || step[3]}` : ""}${trailing}`;
    const flow = core.match(/^(\d+)\s*步(创建|改进)流程$/);
    if (flow) return `${leading}${flow[1]}-step ${flow[2] === "创建" ? "creation" : "improvement"} workflow${trailing}`;
    const accepted = core.match(/^(\d+)\s*项已接受$/);
    if (accepted) return `${leading}${accepted[1]} accepted${trailing}`;
    const conflicts = core.match(/^冲突\s+(\d+)$/);
    if (conflicts) return `${leading}${conflicts[1]} conflicts${trailing}`;
    const weight = core.match(/^已启用维度的权重合计必须为 100%，当前为 (\d+)%?。$/);
    if (weight) return `${leading}Enabled dimensions must total 100%; current total: ${weight[1]}%.${trailing}`;
    const days = core.match(/^(\d+(?:\.\d+)?)\s*\/\s*天$/);
    if (days) return `${leading}${days[1]} / day${trailing}`;
    const pricebook = core.match(/^模型列表来自后端连接测试；每次调用会固定实际模型、输入摘要、用量、耗时和请求 ID。费用由服务端价格表 (.+) 计算。$/);
    if (pricebook) return `${leading}The model list comes from the backend connection test. Each call records the actual model, input digest, usage, duration, and request ID. Cost uses server pricebook ${pricebook[1]}.${trailing}`;
    const expertSummary = core.match(/^(\d+) 个模拟席位、(\d+) 个加权维度；不代表外部专家背书，也不批准发布。$/);
    if (expertSummary) return `${leading}${expertSummary[1]} simulated seats, ${expertSummary[2]} weighted dimensions; no external endorsement or release authorization.${trailing}`;
    const expertBinding = core.match(/^证据下限\s+([^·]+?)\s+·\s+绑定\s+(.+)$/);
    if (expertBinding) return `${leading}Evidence ceiling ${expertBinding[1].trim()} · bound to ${expertBinding[2]}${trailing}`;
    const weightLabel = core.match(/^(.+)权重$/);
    if (weightLabel) return `${leading}${EN[weightLabel[1]] || weightLabel[1]} weight${trailing}`;
    const scoreLabel = core.match(/^(.+)评分$/);
    if (scoreLabel) return `${leading}${EN[scoreLabel[1]] || scoreLabel[1]} score${trailing}`;
    const workflowStep = core.match(/^流程步骤\s+(\d+)$/);
    if (workflowStep) return `${leading}Workflow step ${workflowStep[1]}${trailing}`;
    const removeStep = core.match(/^删除流程步骤\s+(\d+)$/);
    if (removeStep) return `${leading}Remove workflow step ${removeStep[1]}${trailing}`;

    let translated = core;
    Object.keys(EN)
      .filter(key => key.length >= 4 && translated.includes(key))
      .sort((a, b) => b.length - a.length)
      .forEach(key => { translated = translated.replaceAll(key, EN[key]); });
    return `${leading}${translated}${trailing}`;
  }

  function localize(root = document.body) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => {
      if (node.parentElement?.closest("script, style, [data-ai-output]")) return;
      if (/[\u3400-\u9fff]/.test(node.nodeValue || "")) originalText.set(node, node.nodeValue);
      const source = originalText.get(node);
      if (source !== undefined) node.nodeValue = language === "en" ? translate(source) : source;
    });

    const elements = root.matches?.("*") ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
    elements.forEach(element => {
      let saved = originalAttributes.get(element);
      if (!saved) {
        saved = {};
        originalAttributes.set(element, saved);
      }
      attributes.forEach(attribute => {
        const current = element.getAttribute(attribute);
        if (current && /[\u3400-\u9fff]/.test(current)) saved[attribute] = current;
        if (saved[attribute] !== undefined) element.setAttribute(attribute, language === "en" ? translate(saved[attribute]) : saved[attribute]);
      });
    });
  }

  function updateLanguageControls() {
    document.documentElement.lang = language;
    document.title = language === "en" ? "SkillSentra Studio · Visual Skill Lifecycle" : "SkillSentra Studio · 双路径创建工作台";
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = language === "en"
      ? "SkillSentra Studio visual workspace for creating and improving Skills"
      : "SkillSentra Studio 双路径 Skill 创建工作台交互原型";
    document.querySelectorAll("[data-language]").forEach(button => {
      const selected = button.dataset.language === language;
      button.classList.toggle("is-selected", selected);
      button.setAttribute("aria-pressed", String(selected));
    });
  }

  function setLanguage(nextLanguage) {
    language = nextLanguage === "en" ? "en" : "zh-CN";
    localStorage.setItem("skillsentra.language", language);
    updateLanguageControls();
    localize(document.body);
    document.dispatchEvent(new CustomEvent("skillsentra:languagechange", { detail: { language } }));
  }

  updateLanguageControls();
  window.SkillSentraI18n = {
    get language() { return language; },
    isEnglish: () => language === "en",
    localize,
    setLanguage,
    translate
  };
